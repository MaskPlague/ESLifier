def test_bsas_are_sent_for_extraction_using_the_winning_copy(mo2):
    fake, mods, overwrite, _ = mo2
    low = touch(mods / "Low" / "Shared.bsa")
    high = touch(mods / "High" / "Shared.bsa")
    only = touch(mods / "Low" / "Other - Textures.bsa")
    touch(mods / "Low" / "Skyrim - Misc.bsa")                     # blacklisted
    touch(mods / "Low" / "sub" / "Deep.bsa")                      # not at mod root
    plugins = ["x"]
    gather(mods, overwrite, ["Low", "High"], [BSA_MOD, "Low", "High", OVERWRITE_MOD], plugins)
    (bsa_list, passed_plugins), = fake.bsa_calls
    assert passed_plugins is plugins
    # (the path is built from the lower-cased file name, which is fine on Windows, so compare ignoring case)
    assert sorted((n, path.lower()) for n, path in bsa_list) == sorted([("shared", high.lower()), ("other", only.lower())])
    assert low.lower() not in [path.lower() for _, path in bsa_list]


def test_overwrite_bsa_beats_mod_bsa(mo2):
    fake, mods, overwrite, _ = mo2
    touch(mods / "ModA" / "Shared.bsa")
    over = touch(overwrite / "Shared.bsa")
    gather(mods, overwrite, ["ModA"], [BSA_MOD, "ModA", OVERWRITE_MOD])
    (name, path), = fake.bsa_calls[0][0]
    assert name == "shared" and path.lower() == over.lower()


def test_files_extracted_from_bsas_are_attributed_to_the_bsa_sentinel(mo2):
    fake, mods, overwrite, _ = mo2
    fake.files_to_extract = [p("scripts", "s.pex")]
    files, _, cases = gather(mods, overwrite, [], [BSA_MOD, OVERWRITE_MOD])
    assert files == {p("scripts", "s.pex"): [BSA_MOD]}
    assert cases[p("scripts", "s.pex")] == p("scripts", "s.pex")


# ------------------------------------------------------------------------------ get_winning_files
def winners(fake):
    return {k: v[0] for k, v in fake.winning_files_dict.items()}


def test_later_load_order_wins_and_unique_files_pass_through(mo2):
    fake, mods, overwrite, set_modlist = mo2
    set_modlist("+High", "+Low")                                   # High is first line = highest priority
    low = touch(mods / "Low" / "meshes" / "a.nif")
    high = touch(mods / "High" / "meshes" / "a.nif")
    only_low = touch(mods / "Low" / "meshes" / "only_low.nif")
    files, _ = MO2.get_winning_files([])
    assert high in files and low not in files and only_low in files
    assert winners(fake) == {p("meshes", "a.nif"): "High", p("meshes", "only_low.nif"): "Low"}
    assert fake.winning_files_dict[p("meshes", "a.nif")][1] == high


def test_overwrite_folder_beats_every_mod(mo2):
    fake, mods, overwrite, set_modlist = mo2
    set_modlist("+ModA")
    touch(mods / "ModA" / "meshes" / "a.nif")
    over = touch(overwrite / "meshes" / "a.nif")
    files, _ = MO2.get_winning_files([])
    assert files == [over]
    assert winners(fake)[p("meshes", "a.nif")] == OVERWRITE_MOD


def test_loose_files_beat_files_extracted_from_bsas(mo2):
    fake, mods, overwrite, set_modlist = mo2
    set_modlist("+ModA")
    fake.files_to_extract = [p("scripts", "a.pex"), p("scripts", "only_bsa.pex")]
    loose = touch(mods / "ModA" / "scripts" / "a.pex")
    files, _ = MO2.get_winning_files([])
    assert loose in files
    bsa_only = os.path.join(os.getcwd(), "bsa_extracted", p("scripts", "only_bsa.pex"))
    assert bsa_only in files
    assert winners(fake)[p("scripts", "only_bsa.pex")] == BSA_MOD


def test_disabled_mods_do_not_contribute(mo2):
    fake, mods, overwrite, set_modlist = mo2
    set_modlist("+On", "-Off")
    touch(mods / "On" / "a.txt")
    touch(mods / "Off" / "a.txt")
    touch(mods / "Off" / "b.txt")
    files, _ = MO2.get_winning_files([])
    assert files == [str(mods / "On" / "a.txt")]


def test_output_mod_is_never_recorded_as_the_winner(mo2):
    fake, mods, overwrite, set_modlist = mo2
    set_modlist("+ESLifier Output", "+ModA")                       # output mod has top priority
    touch(mods / "ModA" / "meshes" / "a.nif")
    out_file = touch(mods / "ESLifier Output" / "meshes" / "a.nif")
    only_out = touch(mods / "ESLifier Output" / "meshes" / "only_out.nif")
    files, _ = MO2.get_winning_files([])
    assert out_file in files and only_out in files                 # still winning files...
    # ...but the winner recorded for a contested file is the mod underneath, and output-only files are unrecorded
    assert fake.winning_files_dict[p("meshes", "a.nif")] == ("ModA", str(mods / "ModA" / "meshes" / "a.nif"))
    assert p("meshes", "only_out.nif") not in fake.winning_files_dict


def test_plugins_are_returned_with_original_casing_and_cell_master_excluded(mo2):
    fake, mods, overwrite, set_modlist = mo2
    set_modlist("+ModA", "+ModB")
    touch(mods / "ModA" / "Mixed Case.ESP")
    touch(mods / "ModA" / "sub" / "Nested.esp")                    # not at the mod root
    touch(mods / "ModB" / "ESLifier_Cell_Master.esm")
    touch(overwrite / "Over.esl")
    _, plugins = MO2.get_winning_files([])
    assert sorted(os.path.basename(x) for x in plugins) == ["Mixed Case.ESP", "Over.esl"]
    assert str(mods / "ModA" / "Mixed Case.ESP") in plugins


def test_plugin_with_same_name_in_two_mods_is_listed_once_from_the_winner(mo2):
    fake, mods, overwrite, set_modlist = mo2
    set_modlist("+High", "+Low")
    touch(mods / "Low" / "Same.esp")
    touch(mods / "High" / "Same.esp")
    _, plugins = MO2.get_winning_files([])
    assert plugins == [str(mods / "High" / "Same.esp")]


