"""
scanner_mo2.MO2: reads MO2's modlist.txt / ModOrganizer.ini and works out which mod wins each file.
Real folder trees are built in a temp dir; the BSA extractor is replaced by a recorder.

MO2's modlist.txt lists the HIGHEST priority mod first; ESLifier reverses it so the last entry wins.
"""
import os

import pytest

from data_holder import _global
from scanner_fakes import FakeScanner, touch
from scanner_mo2 import MO2, MO2Errors

BSA_MOD = "archive_extracted_eslifier_scan"
OVERWRITE_MOD = "overwrite_eslifier_scan"


def p(*parts):
    """Relative path with the platform separator."""
    return os.path.join(*parts)


@pytest.fixture
def mo2(workdir, monkeypatch):
    """MO2 wired to a fake scanner, with a mods folder, overwrite folder and modlist.txt in the temp dir."""
    fake = FakeScanner()
    monkeypatch.setattr(MO2, "scanner", fake)
    mods = workdir / "mods"
    overwrite = workdir / "overwrite"
    mods.mkdir()
    modlist = workdir / "modlist.txt"
    _global.mo2_mods_folder = str(mods)
    _global.mo2_overwrite_path = str(overwrite)
    _global.mo2_modlist_txt_path = str(modlist)

    def set_modlist(*lines, header=True):
        text = ("# This file was automatically generated by Mod Organizer.\n" if header else "")
        modlist.write_text(text + "\n".join(lines) + "\n", encoding="utf-8")

    return fake, mods, overwrite, set_modlist


# ------------------------------------------------------------------------------ get_modlist
def test_get_modlist_enabled_set(mo2):
    _, _, _, set_modlist = mo2
    set_modlist("+ModA", "-ModDisabled", "-Group_separator", "+Other_separator", "*Unmanaged: DLC", "+ModB")
    load_order, enabled = MO2.get_modlist()
    assert enabled == {"ModA", "ModB", "Unmanaged: DLC", BSA_MOD, OVERWRITE_MOD}


def test_get_modlist_load_order_is_reversed_with_sentinels_at_the_ends(mo2):
    _, _, _, set_modlist = mo2
    set_modlist("+Top", "-Disabled", "+Bottom", header=False)
    load_order, _ = MO2.get_modlist()
    # last entry has the highest priority: overwrite wins over everything, loose files beat extracted BSA files
    assert load_order == [BSA_MOD, "Bottom", "Disabled", "Top", OVERWRITE_MOD]


def test_get_modlist_drops_separators_from_load_order(mo2):
    _, _, _, set_modlist = mo2
    set_modlist("+A", "-Sep_separator", "+B", header=False)
    load_order, _ = MO2.get_modlist()
    assert "Sep_separator" not in load_order
    assert load_order == [BSA_MOD, "B", "A", OVERWRITE_MOD]


def test_get_modlist_header_comment_does_not_become_a_mod_that_outranks_real_ones(mo2):
    _, _, _, set_modlist = mo2
    set_modlist("+A", "+B")
    load_order, enabled = MO2.get_modlist()
    assert load_order[0] == BSA_MOD and load_order[-1] == OVERWRITE_MOD
    assert load_order.index("B") < load_order.index("A")
    assert not any(m.startswith(("#", "This file was")) for m in enabled)


@pytest.mark.xfail(reason="get_modlist logs the failure to read modlist.txt but then indexes load_order[0] on the "
                          "empty list and raises IndexError", strict=False)
def test_missing_modlist_is_reported_and_gives_only_the_sentinels(mo2, log):
    _global.mo2_modlist_txt_path = "does/not/exist.txt"
    load_order, enabled = MO2.get_modlist()
    assert any("Failed to get modlist at" in e for e in log.errors)
    assert load_order == [BSA_MOD, OVERWRITE_MOD]


# ------------------------------------------------------------------------------ get_files_from_mods
def gather(mods, overwrite, enabled, load_order, plugins=None):
    return MO2.get_files_from_mods(str(mods), set(enabled), plugins or [], str(overwrite), load_order)


def test_collects_files_per_mod_keyed_by_lowercase_relative_path(mo2):
    fake, mods, overwrite, _ = mo2
    touch(mods / "ModA" / "Meshes" / "A.nif")
    touch(mods / "ModB" / "meshes" / "a.nif")
    touch(mods / "ModB" / "textures" / "t.dds")
    files, plugin_names, cases = gather(mods, overwrite, ["ModA", "ModB"], [BSA_MOD, "ModA", "ModB", OVERWRITE_MOD])
    key = p("meshes", "a.nif")
    assert sorted(files[key]) == ["ModA", "ModB"]
    assert files[p("textures", "t.dds")] == ["ModB"]
    assert cases[key] in (p("Meshes", "A.nif"), p("meshes", "a.nif"))      # original casing preserved
    assert cases[p("textures", "t.dds")] == p("textures", "t.dds")


def test_disabled_and_unknown_mod_folders_are_skipped(mo2):
    fake, mods, overwrite, _ = mo2
    touch(mods / "Enabled" / "a.txt")
    touch(mods / "Disabled" / "b.txt")
    (mods / "loose_file.txt").write_text("not a mod")
    files, _, _ = gather(mods, overwrite, ["Enabled"], [BSA_MOD, "Enabled", OVERWRITE_MOD])
    assert list(files) == ["a.txt"]


def test_ignored_files_meta_ini_and_mohidden_are_skipped(mo2):
    fake, mods, overwrite, _ = mo2
    fake.ignored_files = {"readme.txt"}
    touch(mods / "ModA" / "meta.ini")                              # mod root meta.ini is MO2 bookkeeping
    touch(mods / "ModA" / "sub" / "meta.ini")                      # nested meta.ini is a real file
    touch(mods / "ModA" / "readme.txt")
    touch(mods / "ModA" / "meshes" / "hidden.nif.mohidden")
    touch(mods / "ModA" / "dir.mohidden" / "x.nif")
    touch(mods / "ModA" / "meshes" / "ok.nif")
    files, _, _ = gather(mods, overwrite, ["ModA"], [BSA_MOD, "ModA", OVERWRITE_MOD])
    assert sorted(files) == sorted([p("sub", "meta.ini"), p("meshes", "ok.nif")])


def test_plugin_names_come_from_mod_and_overwrite_roots_only(mo2):
    fake, mods, overwrite, _ = mo2
    touch(mods / "ModA" / "ModA.esp")
    touch(mods / "ModA" / "Light.ESL")
    touch(mods / "ModA" / "sub" / "Nested.esp")
    touch(overwrite / "FromOverwrite.esm")
    touch(overwrite / "sub" / "Nested2.esp")
    files, plugin_names, _ = gather(mods, overwrite, ["ModA"], [BSA_MOD, "ModA", OVERWRITE_MOD])
    assert sorted(plugin_names) == ["FromOverwrite.esm", "Light.ESL", "ModA.esp"]


def test_overwrite_files_are_attributed_to_the_overwrite_sentinel(mo2):
    fake, mods, overwrite, _ = mo2
    touch(mods / "ModA" / "meshes" / "a.nif")
    touch(overwrite / "meshes" / "a.nif")
    touch(overwrite / "meshes" / "hidden.nif.mohidden")
    files, _, _ = gather(mods, overwrite, ["ModA"], [BSA_MOD, "ModA", OVERWRITE_MOD])
    assert sorted(files[p("meshes", "a.nif")]) == ["ModA", OVERWRITE_MOD]
    assert p("meshes", "hidden.nif.mohidden") not in files


